def get_weather_with_gemini(city: str) -> Dict[str, Any]:
    """
    Get weather information using Gemini Pro
    """
    try:
        model = genai.GenerativeModel('gemini-1.5-pro')
        
        prompt = f"""
        You are a weather assistant. Provide current weather information for {city}.
        
        Please provide a realistic weather report in the following JSON format:
        {{
            "city": "{city}",
            "temperature": "temperature in celsius",
            "description": "weather description",
            "humidity": "humidity percentage", 
            "wind_speed": "wind speed",
            "feels_like": "feels like temperature",
            "status": "success"
        }}
        
        Make the response engaging and conversational while providing the weather data.
        If the city is not recognized, return {{"status": "error", "message": "City not found"}}.
        """
        
        response = model.generate_content(prompt)
        
        # Try to extract JSON from response
        try:
            # Look for JSON in the response
            response_text = response.text
            if '{' in response_text and '}' in response_text:
                json_start = response_text.find('{')
                json_end = response_text.rfind('}') + 1
                json_str = response_text[json_start:json_end]
                weather_data = json.loads(json_str)
                return weather_data
        except:
            pass
        
        # If JSON parsing fails, return a formatted response
        return {
            "status": "success",
            "city": city,
            "response": response.text,
            "temperature": "Generated by Gemini",
            "description": "Weather information provided by AI"
        }
        
    except Exception as e:
        return {
            "status": "error",
            "message": f"Error getting weather: {str(e)}"
        }

