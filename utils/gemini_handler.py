def recommend_music_from_image(image_bytes: bytes) -> Dict[str, Any]:
    """
    Analyze image mood using Gemini Vision and recommend music using Spotify API
    """
    try:
        print("🎵 Starting music recommendation from image analysis...")
        
        # Initialize Spotify client
        client_id = os.getenv('SPOTIFY_CLIENT_ID')
        client_secret = os.getenv('SPOTIFY_CLIENT_SECRET')
        
        if not client_id or not client_secret:
            return {
                "status": "error",
                "message": "Spotify API credentials not configured. Please add SPOTIFY_CLIENT_ID and SPOTIFY_CLIENT_SECRET to your .env file."
            }
        
        # Set up Spotify client
        client_credentials_manager = SpotifyClientCredentials(
            client_id=client_id,
            client_secret=client_secret
        )
        sp = spotipy.Spotify(client_credentials_manager=client_credentials_manager)
        
        # Analyze image with Gemini Vision
        print("🔍 Analyzing image mood with Gemini Vision...")
        
        # Convert image bytes to PIL Image for processing
        image = Image.open(io.BytesIO(image_bytes))
        
        # Use Gemini Vision model for image analysis
        vision_model = genai.GenerativeModel('gemini-1.5-pro')
        
        mood_prompt = """
        Analyze this image and determine the mood, atmosphere, and emotional tone. 
        Based on what you see, suggest music moods that would match this image.
        Focus on recommending Hindi and Punjabi music that fits the mood.
        
        Consider:
        - Colors and lighting (warm/cool, bright/dark)
        - Setting and environment (urban/nature, indoor/outdoor)
        - People's expressions or body language (if any)
        - Overall vibe and energy level
        - Time of day or season
        
        Think about what type of Hindi or Punjabi songs would fit:
        - High energy: Bollywood dance, Bhangra, party songs
        - Medium energy: Melodic Hindi songs, Punjabi classics
        - Low energy: Romantic Hindi songs, slow Punjabi songs
        
        Respond in this JSON format:
        {
            "primary_mood": "main mood detected",
            "energy_level": "low/medium/high",
            "hindi_style": "romantic/dance/melodic/sad/party",
            "punjabi_style": "bhangra/romantic/folk/dance/slow",
            "keywords": ["keyword1", "keyword2", "keyword3"],
            "time_context": "morning/afternoon/evening/night",
            "description": "detailed description of the mood and why certain Hindi/Punjabi music would fit"
        }
        """
        
        # Analyze the image
        response = vision_model.generate_content([mood_prompt, image])
        
        # Parse the mood analysis
        try:
            response_text = response.text
            if '{' in response_text and '}' in response_text:
                json_start = response_text.find('{')
                json_end = response_text.rfind('}') + 1
                json_str = response_text[json_start:json_end]
                mood_data = json.loads(json_str)
            else:
                # Fallback if JSON parsing fails
                mood_data = {
                    "primary_mood": "relaxed",
                    "energy_level": "medium",
                    "hindi_style": "melodic",
                    "punjabi_style": "folk",
                    "keywords": ["chill", "peaceful"],
                    "description": response_text
                }
        except:
            mood_data = {
                "primary_mood": "happy",
                "energy_level": "medium", 
                "hindi_style": "dance",
                "punjabi_style": "bhangra",
                "keywords": ["upbeat", "positive"],
                "description": "Could not parse mood analysis"
            }
        
        print(f"🎭 Detected mood: {mood_data.get('primary_mood', 'unknown')}")
        
        # Search for music on Spotify based on mood
        print("🔎 Searching for Hindi and Punjabi music on Spotify...")
        
        recommendations = []
        
        # Create dynamic search queries based on actual mood analysis
        search_terms = []
        
        # Extract mood details
        primary_mood = mood_data.get('primary_mood', 'happy')
        energy_level = mood_data.get('energy_level', 'medium')
        hindi_style = mood_data.get('hindi_style', 'melodic')
        punjabi_style = mood_data.get('punjabi_style', 'folk')
        keywords = mood_data.get('keywords', ['music'])
        
        print(f"🎯 Searching for: {primary_mood} mood, {energy_level} energy, Hindi: {hindi_style}, Punjabi: {punjabi_style}")
        
        # Build mood-specific search terms
        mood_specific_terms = []
        
        # Add primary mood-based searches
        if primary_mood in ['peaceful', 'calm', 'serene', 'relaxed']:
            mood_specific_terms.extend([
                f"hindi peaceful {keywords[0] if keywords else 'songs'}", 
                f"bollywood calm romantic",
                f"punjabi slow {keywords[0] if keywords else 'songs'}",
                f"punjabi sufi peaceful"
            ])
        elif primary_mood in ['happy', 'joyful', 'upbeat', 'energetic']:
            mood_specific_terms.extend([
                f"bollywood happy dance",
                f"hindi {keywords[0] if keywords else 'party'} songs",
                f"punjabi bhangra {keywords[0] if keywords else 'dance'}",
                f"punjabi celebration songs"
            ])
        elif primary_mood in ['sad', 'melancholic', 'emotional', 'reflective']:
            mood_specific_terms.extend([
                f"hindi sad {keywords[0] if keywords else 'romantic'}",
                f"bollywood emotional songs",
                f"punjabi sad {keywords[0] if keywords else 'love'} songs",
                f"punjabi dard bhari songs"
            ])
        elif primary_mood in ['romantic', 'love', 'dreamy']:
            mood_specific_terms.extend([
                f"hindi romantic {keywords[0] if keywords else 'love'} songs",
                f"bollywood love songs",
                f"punjabi romantic {keywords[0] if keywords else 'ishq'} songs",
                f"punjabi love ballads"
            ])
        else:
            # Default mood-based searches
            mood_specific_terms.extend([
                f"hindi {primary_mood} songs",
                f"bollywood {primary_mood}",
                f"punjabi {primary_mood} songs",
                f"punjabi {keywords[0] if keywords else 'music'}"
            ])
        
        # Add energy-specific searches
        if energy_level == "high":
            mood_specific_terms.extend([
                f"bollywood dance {keywords[0] if keywords else 'party'}",
                f"punjabi bhangra {keywords[0] if keywords else 'dance'}"
            ])
        elif energy_level == "low":
            mood_specific_terms.extend([
                f"hindi soft {keywords[0] if keywords else 'romantic'}",
                f"punjabi slow {keywords[0] if keywords else 'sufi'}"
            ])
        else:
            mood_specific_terms.extend([
                f"hindi melodic {keywords[0] if keywords else 'classic'}",
                f"punjabi classic {keywords[0] if keywords else 'folk'}"
            ])
        
        # Add keyword-based searches for more variety
        for keyword in keywords[:2]:  # Use first 2 keywords
            mood_specific_terms.extend([
                f"hindi {keyword} songs",
                f"punjabi {keyword} songs"
            ])
        
        # Use the mood-specific terms (limit to 8 unique terms)
        search_terms = list(set(mood_specific_terms))[:8]
        
        print(f"🔍 Search terms: {search_terms}")
        
        # Search for tracks with more variety
        
        # Search for tracks with more variety
        for i, term in enumerate(search_terms):  # Use all search terms for variety
            try:
                # Add some randomization to get different results
                limit = 2 if i < 4 else 1  # More results from first few searches
                offset = (i * 2) % 20  # Add offset to get different results each time
                results = sp.search(q=term, type='track', limit=limit, offset=offset)
                
                for track in results['tracks']['items']:
                    if len(recommendations) >= 10:  # Limit total recommendations
                        break
                        
                    # Get artist names
                    artists = [artist['name'] for artist in track['artists']]
                    
                    # Create clickable Spotify link
                    spotify_url = track['external_urls']['spotify']
                    
                    recommendation = {
                        "name": track['name'],
                        "artists": artists,
                        "spotify_url": spotify_url,
                        "preview_url": track.get('preview_url'),
                        "popularity": track['popularity'],
                        "search_term": term  # Track which search found this song
                    }
                    
                    # Avoid duplicates by checking both name and first artist
                    is_duplicate = any(
                        r['name'].lower() == recommendation['name'].lower() and 
                        r['artists'][0].lower() == recommendation['artists'][0].lower() 
                        for r in recommendations
                    )
                    
                    if not is_duplicate:
                        recommendations.append(recommendation)
                        print(f"🎵 Found: {track['name']} by {', '.join(artists)} (via: {term})")
                        
            except Exception as search_error:
                print(f"Search error for term '{term}': {str(search_error)}")
                continue
                
            # Break if we have enough songs
            if len(recommendations) >= 10:
                break
        
        if not recommendations:
            return {
                "status": "error",
                "message": "Could not find music recommendations. Please try again."
            }
        
        print(f"✅ Found {len(recommendations)} music recommendations!")
        
        return {
            "status": "success",
            "mood_analysis": mood_data,
            "recommendations": recommendations,
            "total_found": len(recommendations)
        }
        
    except Exception as e:
        print(f"❌ Error in music recommendation: {str(e)}")
        return {
            "status": "error",
            "message": f"Error analyzing image for music recommendation: {str(e)}"
        }
