def generate_image_with_gemini(prompt: str) -> Dict[str, Any]:
    """
    Generate actual images using AI image generation APIs
    """
    try:
        print(f"🎨 Generating image for prompt: {prompt}")
        
        # Method 1: Try Pollinations AI (Free, fast, no auth required)
        try:
            print("🔄 Trying Pollinations AI...")
            # URL encode the prompt for safe transmission
            import urllib.parse
            encoded_prompt = urllib.parse.quote(prompt)
            pollinations_url = f"https://image.pollinations.ai/prompt/{encoded_prompt}?width=512&height=512&model=flux"
            
            response = requests.get(pollinations_url, timeout=30)
            
            if response.status_code == 200:
                image_bytes = response.content
                
                # Verify it's a valid image
                if len(image_bytes) > 1000:
                    print("✅ Image generated successfully via Pollinations!")
                    return {
                        "status": "success", 
                        "original_prompt": prompt,
                        "image_bytes": image_bytes,
                        "model": "flux",
                        "source": "pollinations"
                    }
                    
        except Exception as poll_error:
            print(f"❌ Pollinations failed: {str(poll_error)}")
        
        # Method 2: Try Hugging Face Inference API (Free with token)
        try:
            API_URL = "https://api-inference.huggingface.co/models/runwayml/stable-diffusion-v1-5"
            
            headers = {"Content-Type": "application/json"}
            
            # Add Hugging Face token if available
            hf_token = os.getenv('HUGGINGFACE_TOKEN')
            if hf_token:
                headers["Authorization"] = f"Bearer {hf_token}"
            
            payload = {
                "inputs": prompt,
                "parameters": {
                    "num_inference_steps": 25,
                    "guidance_scale": 7.5
                }
            }
            
            print("🔄 Trying Hugging Face API...")
            response = requests.post(API_URL, headers=headers, json=payload, timeout=60)
            
            if response.status_code == 200:
                image_bytes = response.content
                
                # Verify it's a valid image
                if len(image_bytes) > 1000 and (image_bytes[:4] == b'\x89PNG' or image_bytes[:3] == b'\xff\xd8\xff'):
                    print("✅ Image generated successfully via Hugging Face!")
                    return {
                        "status": "success",
                        "original_prompt": prompt,
                        "image_bytes": image_bytes,
                        "model": "stable-diffusion-v1-5",
                        "source": "huggingface"
                    }
            elif response.status_code == 503:
                print("⚠️ Hugging Face model is loading, trying another model...")
                
                # Try alternative model
                alt_url = "https://api-inference.huggingface.co/models/stabilityai/stable-diffusion-2-1"
                alt_response = requests.post(alt_url, headers=headers, json=payload, timeout=60)
                
                if alt_response.status_code == 200:
                    image_bytes = alt_response.content
                    if len(image_bytes) > 1000 and (image_bytes[:4] == b'\x89PNG' or image_bytes[:3] == b'\xff\xd8\xff'):
                        print("✅ Image generated successfully via alternative Hugging Face model!")
                        return {
                            "status": "success",
                            "original_prompt": prompt,
                            "image_bytes": image_bytes,
                            "model": "stable-diffusion-2-1",
                            "source": "huggingface-alt"
                        }
                    
        except Exception as hf_error:
            print(f"❌ Hugging Face failed: {str(hf_error)}")
        
        # Method 3: Try another free API
        try:
            print("🔄 Trying alternative image generation API...")
            alt_url = f"https://image.pollinations.ai/prompt/{encoded_prompt}?width=768&height=768&model=flux-realism"
            
            response = requests.get(alt_url, timeout=30)
            
            if response.status_code == 200:
                image_bytes = response.content
                
                if len(image_bytes) > 1000:
                    print("✅ Image generated successfully via alternative API!")
                    return {
                        "status": "success", 
                        "original_prompt": prompt,
                        "image_bytes": image_bytes,
                        "model": "flux-realism",
                        "source": "pollinations-alt"
                    }
                    
        except Exception as alt_error:
            print(f"❌ Alternative API failed: {str(alt_error)}")
        
        # If all methods fail, return error
        print("❌ All image generation methods failed")
        return {
            "status": "error",
            "message": "Image generation services are temporarily unavailable. Please try again in a few moments."
        }
        
    except Exception as e:
        print(f"❌ Critical error in image generation: {str(e)}")
        return {
            "status": "error",
            "message": f"Error generating image: {str(e)}"
        }

